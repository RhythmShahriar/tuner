// Package export converts Tuner's YAML checks into other scanners'
// formats, so people who already run those scanners can use the checks.
//
// Nuclei templates cover what a template can express: GET or HEAD
// requests and status, word, regex and header matchers. Tuner's soft-404
// comparison has no Nuclei equivalent; a check that also matches on
// content gets a negative matcher for "404" and "not found" page titles
// instead. A check that relies on the comparison alone is skipped.
// TLS, scheme and cookie conditions are skipped with a reason too.
package export

import (
	"bytes"
	"fmt"
	"regexp"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/RhythmShahriar/tuner/engine"
	"github.com/RhythmShahriar/tuner/matchers"
)

// NucleiPrefix starts every exported template ID, so Tuner's templates
// never collide with nuclei-templates.
const NucleiPrefix = "tuner-"

// Soft404Title is the negative matcher that stands in for Tuner's soft-404
// comparison: a page whose title says 404 or not found is an error page,
// whatever its status.
const Soft404Title = `(?i)<title>[^<]*(?:404|not found)`

// Template is one check converted for Nuclei.
type Template struct {
	CheckID string // the Tuner check ID
	File    string // file name, tuner-<id>.yaml
	Data    []byte // the template; nil when Skipped is set

	// Skipped says why the check has no template.
	Skipped string
	// Soft404 is set when the soft-404 comparison became Soft404Title.
	Soft404 bool
}

// Options describe the export.
type Options struct {
	Version string // rhythm-tuner version, for the generated-by comment
}

// Nuclei converts each check, in order.
func Nuclei(checks []*engine.Check, opts Options) []Template {
	out := make([]Template, 0, len(checks))
	for _, c := range checks {
		out = append(out, NucleiTemplate(c, opts))
	}
	return out
}

// NucleiTemplate converts one check.
func NucleiTemplate(c *engine.Check, opts Options) Template {
	t := Template{CheckID: c.ID, File: NucleiPrefix + c.ID + ".yaml"}
	ms, soft404, reason := nucleiMatchers(c.Match)
	if reason != "" {
		t.Skipped = reason
		return t
	}
	t.Soft404 = soft404

	paths := make([]string, len(c.Request.Path))
	for i, p := range c.Request.Path {
		// Nuclei's {{Host}} is the host name without the port, like
		// Tuner's {{host}}.
		paths[i] = "{{BaseURL}}" + strings.ReplaceAll(p, "{{host}}", "{{Host}}")
	}
	meta := nucleiMeta{
		MaxRequest: len(paths),
		TunerID:    c.ID,
		Profile:    string(c.Profile),
		Requires:   strings.Join(c.Requires, ","),
		FixNginx:   strings.TrimSpace(c.FixServer.Nginx),
		FixApache:  strings.TrimSpace(c.FixServer.Apache),
	}
	if c.Confidence != engine.ConfidenceHigh {
		meta.Confidence = string(c.Confidence)
	}
	tmpl := nucleiTemplate{
		ID: NucleiPrefix + c.ID,
		Info: nucleiInfo{
			Name:        c.Name,
			Author:      "rhythm-tuner",
			Severity:    string(c.Severity),
			Description: strings.TrimSpace(c.Impact),
			Remediation: strings.TrimSpace(c.Fix),
			Reference:   c.References,
			Tags:        strings.Join(append([]string{"tuner"}, c.Tags...), ","),
			Metadata:    meta,
		},
		HTTP: []nucleiRequest{{
			Method:            strings.ToUpper(c.Request.Method),
			Path:              paths,
			StopAtFirstMatch:  len(paths) > 1,
			MatchersCondition: "and",
			Matchers:          ms,
		}},
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by rhythm-tuner %s from the Tuner check %s (%s).\n", opts.Version, c.ID, c.File)
	b.WriteString("# MIT license, see README.md. Edit the check, not this file: https://github.com/RhythmShahriar/tuner\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(tmpl); err != nil {
		// Only plain strings, ints and bools go in, which always encode.
		panic(err)
	}
	_ = enc.Close()
	t.Data = b.Bytes()
	return t
}

// The template layout, in the field order nuclei-templates use.
type nucleiTemplate struct {
	ID   string          `yaml:"id"`
	Info nucleiInfo      `yaml:"info"`
	HTTP []nucleiRequest `yaml:"http"`
}

type nucleiInfo struct {
	Name        string     `yaml:"name"`
	Author      string     `yaml:"author"`
	Severity    string     `yaml:"severity"`
	Description string     `yaml:"description,omitempty"`
	Remediation string     `yaml:"remediation,omitempty"`
	Reference   []string   `yaml:"reference,omitempty"`
	Tags        string     `yaml:"tags"`
	Metadata    nucleiMeta `yaml:"metadata"`
}

type nucleiMeta struct {
	MaxRequest int    `yaml:"max-request"`
	TunerID    string `yaml:"tuner-id"`
	Profile    string `yaml:"tuner-profile"`
	Confidence string `yaml:"tuner-confidence,omitempty"`
	Requires   string `yaml:"tuner-requires,omitempty"`
	FixNginx   string `yaml:"fix-nginx,omitempty"`
	FixApache  string `yaml:"fix-apache,omitempty"`
}

type nucleiRequest struct {
	Method            string          `yaml:"method"`
	Path              []string        `yaml:"path"`
	StopAtFirstMatch  bool            `yaml:"stop-at-first-match,omitempty"`
	MatchersCondition string          `yaml:"matchers-condition"`
	Matchers          []nucleiMatcher `yaml:"matchers"`
}

type nucleiMatcher struct {
	Type      string   `yaml:"type"`
	Part      string   `yaml:"part,omitempty"`
	Status    []int    `yaml:"status,omitempty,flow"`
	Words     []string `yaml:"words,omitempty"`
	Regex     []string `yaml:"regex,omitempty"`
	DSL       []string `yaml:"dsl,omitempty"`
	Condition string   `yaml:"condition,omitempty"`
	Negative  bool     `yaml:"negative,omitempty"`
}

// nucleiMatchers turns a match block into matchers that must all hold, or
// says why it can't. An any block becomes one matcher when every
// alternative is a single body pattern of the same kind.
func nucleiMatchers(b matchers.Block) (out []nucleiMatcher, soft404 bool, reason string) {
	for _, m := range b.All {
		ms, base, why := fields(m)
		if why != "" {
			return nil, false, why
		}
		out = append(out, ms...)
		soft404 = soft404 || base
	}
	switch len(b.Any) {
	case 0:
	case 1:
		ms, base, why := fields(b.Any[0])
		if why != "" {
			return nil, false, why
		}
		out = append(out, ms...)
		soft404 = soft404 || base
	default:
		m, base, why := anyOf(b.Any)
		if why != "" {
			return nil, false, why
		}
		out = append(out, m)
		soft404 = soft404 || base
	}
	if soft404 {
		if !slices.ContainsFunc(out, content) {
			return nil, false, "only the soft-404 comparison tells the real file from an error page; Nuclei has no such matcher"
		}
		out = append(out, nucleiMatcher{Type: "regex", Part: "body", Regex: []string{Soft404Title}, Negative: true})
	}
	return out, soft404, ""
}

// content reports whether m looks for something only the real response
// has, which makes the soft-404 stand-in safe.
func content(m nucleiMatcher) bool {
	return !m.Negative && m.Part != "header" && (len(m.Words) > 0 || len(m.Regex) > 0 || len(m.DSL) > 0)
}

// fields converts every condition of one Tuner matcher; they must all hold.
func fields(m matchers.Matcher) (out []nucleiMatcher, soft404 bool, reason string) {
	switch {
	case m.TLS != nil:
		return nil, false, "TLS conditions need a TLS probe, which a Nuclei http template has not"
	case m.Cookie != nil:
		return nil, false, "cookie flag conditions have no Nuclei matcher"
	case m.Scheme != "":
		return nil, false, "the scheme condition (" + m.Scheme + " only) has no Nuclei matcher"
	}
	if len(m.Status) > 0 {
		out = append(out, nucleiMatcher{Type: "status", Status: m.Status})
	}
	if m.Magic != "" {
		out = append(out, nucleiMatcher{Type: "dsl", DSL: []string{magicDSL(m.Magic)}})
	}
	if len(m.Words) > 0 {
		out = append(out, nucleiMatcher{Type: "word", Part: "body", Words: m.Words})
	}
	if m.Regex != "" {
		out = append(out, nucleiMatcher{Type: "regex", Part: "body", Regex: []string{m.Regex}})
	}
	if m.NotRegex != "" {
		out = append(out, nucleiMatcher{Type: "regex", Part: "body", Regex: []string{m.NotRegex}, Negative: true})
	}
	for _, name := range sortedKeys(m.Header) {
		out = append(out, nucleiMatcher{Type: "regex", Part: "header", Regex: []string{headerRegex(name, m.Header[name])}})
	}
	for _, name := range sortedKeys(m.NotHeader) {
		out = append(out, nucleiMatcher{Type: "regex", Part: "header", Regex: []string{headerRegex(name, m.NotHeader[name])}, Negative: true})
	}
	for _, name := range m.MissingHeader {
		out = append(out, nucleiMatcher{Type: "regex", Part: "header", Regex: []string{headerRegex(name, "")}, Negative: true})
	}
	return out, m.NotBaseline, ""
}

// anyOf merges the alternatives of an any block into one matcher that
// holds when one of them does. Nuclei matchers can't nest, so each
// alternative must be one body pattern (words and regexes merge into
// regexes) or all must be magic bytes; not_baseline on an alternative
// counts for the whole block.
func anyOf(alts []matchers.Matcher) (nucleiMatcher, bool, string) {
	var regex, dsl []string
	soft404 := false
	for _, a := range alts {
		ms, base, why := fields(a)
		if why != "" {
			return nucleiMatcher{}, false, why
		}
		soft404 = soft404 || base
		if len(ms) != 1 || ms[0].Negative || ms[0].Part == "header" || ms[0].Type == "status" {
			return nucleiMatcher{}, false, "an any alternative with more than one condition, or one that is not a body pattern, has no Nuclei equivalent"
		}
		switch m := ms[0]; m.Type {
		case "dsl":
			dsl = append(dsl, m.DSL...)
		case "word":
			for _, w := range m.Words {
				regex = append(regex, regexp.QuoteMeta(w))
			}
		default:
			regex = append(regex, m.Regex...)
		}
	}
	switch {
	case len(dsl) > 0 && len(regex) > 0:
		return nucleiMatcher{}, false, "an any block that mixes magic bytes with text patterns has no Nuclei equivalent"
	case len(dsl) > 0:
		return nucleiMatcher{Type: "dsl", DSL: dsl, Condition: "or"}, soft404, ""
	}
	return nucleiMatcher{Type: "regex", Part: "body", Regex: regex, Condition: "or"}, soft404, ""
}

// magicDSL checks that the body starts with the given bytes. A binary
// matcher would find them anywhere in the body, which is weaker.
func magicDSL(magic string) string {
	return fmt.Sprintf(`starts_with(hex_encode(body), %q)`, strings.ToLower(magic))
}

// headerRegex matches the header section for a header whose value
// matches value, the way Tuner matches each value of the header. An empty
// value only asks that the header is there.
func headerRegex(name, value string) string {
	re := `(?mi)^` + regexp.QuoteMeta(name) + `:[ \t]*`
	if value == "" {
		return re
	}
	// The value regex keeps its own case rules; ^ and $ refer to the
	// value, so they become the start after the colon and the line end.
	anchored := strings.HasPrefix(value, "^")
	value = strings.TrimPrefix(value, "^")
	if strings.HasSuffix(value, "$") && !strings.HasSuffix(value, `\$`) {
		value = strings.TrimSuffix(value, "$") + `[ \t]*\r?$`
	}
	if !anchored {
		value = `[^\r\n]*?` + value
	}
	return re + `(?-i:` + value + `)`
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
