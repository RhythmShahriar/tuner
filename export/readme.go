package export

import (
	"bytes"
	"fmt"
	"strings"
)

// NucleiREADME describes an export: how to run the templates, how they
// differ from Tuner's checks, the checks left out and the license text
// the templates ship under.
func NucleiREADME(ts []Template, opts Options, license string) []byte {
	var written, soft404 int
	var skipped []string
	for _, t := range ts {
		if t.Skipped != "" {
			skipped = append(skipped, fmt.Sprintf("- `%s`: %s", t.CheckID, t.Skipped))
			continue
		}
		written++
		if t.Soft404 {
			soft404++
		}
	}

	var b bytes.Buffer
	b.WriteString("# Tuner checks as Nuclei templates\n\n")
	fmt.Fprintf(&b, "%s, generated by rhythm-tuner %s with\n", templates(written), opts.Version)
	b.WriteString("`rhythm tuner checks export --nuclei`. Each `tuner-<id>.yaml` file is one\n")
	b.WriteString("Tuner check. The fix for each finding is in `info.remediation`. The\n")
	b.WriteString("nginx and Apache snippets are in `info.metadata` as `fix-nginx` and\n")
	b.WriteString("`fix-apache`.\n\n")
	b.WriteString("Run them with:\n\n")
	b.WriteString("```\nnuclei -t . -u https://example.com\n```\n\n")
	b.WriteString("Every template sends only GET or HEAD requests for files a site already\n")
	b.WriteString("serves. None sends a payload.\n\n")

	b.WriteString("## How they differ from Tuner\n\n")
	b.WriteString("- Tuner compares each hit with the site's answer for a random path of the\n")
	b.WriteString("  same shape, so a site that answers every URL with the same page reports\n")
	verb := "use"
	if soft404 == 1 {
		verb = "uses"
	}
	fmt.Fprintf(&b, "  nothing. Nuclei can't, so %s %s a negative matcher instead:\n", templates(soft404), verb)
	b.WriteString("  a page whose title says 404 or not found is never a finding. Expect a\n")
	b.WriteString("  few more false positives on catch-all sites than with `rhythm tuner scan`.\n")
	b.WriteString("- Tuner runs WordPress, PHP and Laravel checks only on sites built with\n")
	b.WriteString("  them (`tuner-requires` in the metadata). These templates run on every site.\n")
	b.WriteString("- Tuner masks secrets in every report. Nuclei can store full responses\n")
	b.WriteString("  (`-store-resp`), secrets included.\n")

	b.WriteString("\n## Checks left out\n\n")
	if len(skipped) == 0 {
		b.WriteString("None.\n")
	} else {
		b.WriteString("These checks need conditions a Nuclei http template can't express. Run\n")
		b.WriteString("`rhythm tuner scan` for them.\n\n")
		b.WriteString(strings.Join(skipped, "\n") + "\n")
	}

	b.WriteString("\n## License\n\n")
	b.WriteString("The checks and so these templates are MIT licensed (the rest of Tuner is\n")
	b.WriteString("AGPL-3.0). Source: https://github.com/RhythmShahriar/tuner/tree/main/checks\n\n")
	b.WriteString("```\n" + strings.TrimSpace(license) + "\n```\n")
	return b.Bytes()
}

// templates is "1 template" or "n templates".
func templates(n int) string {
	if n == 1 {
		return "1 template"
	}
	return fmt.Sprintf("%d templates", n)
}
