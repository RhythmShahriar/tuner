package main

import (
	"fmt"
	"runtime"
	"slices"
	"strings"
	"time"
)

// board holds every tool's score on every site, in a stable order.
type board struct {
	manifest *Manifest
	sites    []string // site names, in a fixed order
	// scores[tool.Key][site] is one Score.
	scores map[string]map[string]Score
}

// newBoard records scores keyed by tool and site.
func newBoard(m *Manifest, sites []string, scores []Score) *board {
	b := &board{manifest: m, sites: sites, scores: map[string]map[string]Score{}}
	for _, s := range scores {
		if b.scores[toolKey(s.Tool)] == nil {
			b.scores[toolKey(s.Tool)] = map[string]Score{}
		}
		b.scores[toolKey(s.Tool)][s.Site] = s
	}
	return b
}

func toolKey(name string) string {
	for _, t := range allTools {
		if t.Name == name || t.Key == name {
			return t.Key
		}
	}
	return strings.ToLower(name)
}

// scoreboard renders docs/benchmark.md.
func scoreboard(b *board, version string, when time.Time) string {
	var sb strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&sb, format, a...) }

	w("<!-- Generated by `go run -tags testbed ./testbed/bench`. Don't edit by hand: rerun the benchmark. -->\n\n")
	w("# Tuner benchmark\n\n")
	w("The testbed (`testbed/docker-compose.yml`) is a WordPress site with %d plugins, an old core and files left on show, ", len(b.manifest.Plugins))
	w("served by nginx and Apache, plus a subfolder install and a WAF-challenge front. ")
	w("`testbed/ground-truth.yaml` says what is really installed and really exposed. ")
	w("For every tool the benchmark runs one scan per site and scores it against that truth: ")
	w("plugins found, false positives, requests and time. Only Tuner looks for exposed files, so those are Tuner's columns alone.\n\n")

	ver := version
	if ver == "" {
		ver = "a development build"
	}
	w("Run on %s with rhythm-tuner %s (%s/%s).\n\n", when.UTC().Format("2006-01-02"), ver, runtime.GOOS, runtime.GOARCH)

	// Plugin recall on the main site, the headline.
	main := "main"
	if !slices.Contains(b.sites, main) {
		main = b.sites[0]
	}
	total := len(b.manifest.Plugins)
	vulnTotal := len(b.manifest.VulnerableSlugs())
	w("## Plugins found on the main site\n\n")
	w("%d plugins installed, %d of them flagged by public advisories.\n\n", total, vulnTotal)
	w("| Tool | Plugins found | Vulnerable found | False positives | Requests | Time |\n")
	w("|---|---|---|---|---|---|\n")
	for _, t := range allTools {
		s := b.scores[t.Key][main]
		if s.NotRun {
			w("| %s | not run | | | | |\n", t.Name)
			continue
		}
		if s.Error != "" {
			w("| %s | error | | | | |\n", t.Name)
			continue
		}
		w("| %s | %d / %d | %d / %d | %d | %s | %s |\n",
			t.Name, len(s.Found), total, len(s.VulnFound), vulnTotal, len(s.FalsePos),
			requests(s.Requests), s.Duration.Round(100*time.Millisecond))
	}
	w("\n")

	// Exposed files, Tuner only.
	w("## Exposed files (Tuner)\n\n")
	site := b.manifest.Sites[main]
	if len(site.Exposed) == 0 {
		w("None listed for the main site.\n\n")
	} else {
		s := b.scores["tuner"][main]
		w("%d of %d reported.\n\n", len(s.FilesFound), len(site.Exposed))
		w("| File | Expected | Reported |\n|---|---|---|\n")
		for _, e := range site.Exposed {
			rep := "missed"
			if slices.Contains(s.FilesFound, e.Path) {
				rep = "**found**"
			}
			w("| `%s` | %s (%s) | %s |\n", e.Path, e.Finding, e.Severity, rep)
		}
		w("\n")
	}

	// Other sites.
	w("## Other sites\n\n")
	w("| Site | Front | Tool | Result |\n|---|---|---|---|\n")
	for _, name := range b.sites {
		if name == main {
			continue
		}
		site := b.manifest.Sites[name]
		for _, t := range allTools {
			s := b.scores[t.Key][name]
			w("| %s | %s | %s | %s |\n", name, site.Front, t.Name, result(site, s))
		}
	}
	w("\n")

	w("## How each tool was run\n\n")
	for _, t := range allTools {
		w("- **%s**: %s\n", t.Name, t.About)
	}
	w("\nWPScan runs with no API token, so its advisory data is not exercised here; this benchmark measures detection, not advisories. ")
	w("Nothing in the testbed is a real secret or a working exploit.\n")
	return sb.String()
}

func requests(n int64) string {
	if n < 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d", n)
}

// result is a one-line outcome for a non-main site.
func result(site Site, s Score) string {
	switch {
	case s.NotRun:
		return "not run"
	case s.Error != "":
		return "error: " + firstLine(s.Error)
	case site.Blocked && s.Blocked:
		return "**blocked** (correct)"
	case site.Blocked && !s.Blocked:
		return "scanned a challenge page as the site"
	default:
		return fmt.Sprintf("%d plugins, %d false", len(s.Found), len(s.FalsePos))
	}
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 80 {
		s = s[:80] + "..."
	}
	return s
}
